// Package directive holds the GraphQL SDL definitions for octoqlgen's directives.
package directive

// Name is the directive for options on the node it is attached to.
const Name = "octoqlgen"

// DefaultsName is the directive for default options on fields inside an
// operation or fragment.
const DefaultsName = "octoqlgenDefaults"

// ForName is the directive for options on a named type's field.
const ForName = "octoqlgenFor"

// SDL declares octoqlgen's directives.
const SDL = `directive @` + Name + `(
  """Omit this variable, or input-type field, when its value is empty."""
  omitempty: Boolean

  """Whether the value uses a pointer type in Go."""
  pointer: Boolean

  """Use a struct for this field even though its type is an interface."""
  struct: Boolean

  """Use the generated type of this field's single fragment spread directly."""
  flatten: Boolean

  """
  Fully qualified Go type to use instead of a generated one, such as
  "time.Time". Use "-" to opt out of a configured binding.
  """
  bind: String

  """Name for the Go type generated from this node."""
  typename: String

  """Go name for this selected field, without adding a GraphQL alias."""
  alias: String
) repeatable on QUERY | MUTATION | FIELD | FRAGMENT_DEFINITION | VARIABLE_DEFINITION

directive @` + DefaultsName + `(
  """Default omitempty for the variables and input-type fields inside."""
  omitempty: Boolean

  """Default pointer for the fields inside."""
  pointer: Boolean

  """Default struct for the interface-typed fields inside."""
  struct: Boolean
) repeatable on QUERY | MUTATION | FRAGMENT_DEFINITION

directive @` + ForName + `(
  """The field these options apply to, written as "MyType.myField"."""
  field: String!

  """Omit that field when its value is empty."""
  omitempty: Boolean

  """Whether that field uses a pointer type in Go."""
  pointer: Boolean

  """
  Fully qualified Go type to use for that field instead of a generated one.
  Use "-" to opt out of a configured binding.
  """
  bind: String

  """Name for the Go type generated from that field."""
  typename: String

  """
  Go name for that field, without adding a GraphQL alias.  Only applicable
  when it is a selected field, not an input-type field.
  """
  alias: String
) repeatable on QUERY | MUTATION | FRAGMENT_DEFINITION
`

// FileName is the companion schema file name for octoqlgen's directive SDL.
const FileName = "octoqlgen-directive.graphql"

// FileHeader identifies companion files generated by octoqlgen.
const FileHeader = "# Code generated by octoqlgen. DO NOT EDIT.\n"

// FileContents is the companion file octoqlgen writes next to a schema.
const FileContents = FileHeader + `#
# This file declares octoqlgen's directives so editors and other GraphQL tooling
# can resolve them in your operations. It is not part of any schema you fetched, and
# the generator uses its own copy of this declaration, so editing this file
# changes nothing except what your editor reports.
#
# Point your GraphQL tooling at this file alongside your schema. Many setups
# already read every .graphql file in the project; those that take a list, such
# as graphql-config, need it added:
#
#   schema:
#     - schema.graphql
#     - ` + FileName + `
#
# Declare them in exactly one place per project. GraphQL does not allow a
# directive to be declared twice, so tooling that reads several schema files at
# once reports an error if more than one of them declares @` + Name + `.

` + SDL
